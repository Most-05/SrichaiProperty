export interface Profile {
  /** ชื่อ-นามสกุลจริงของผู้ใช้งาน */
  fullName: string;
  /** เบอร์โทรศัพท์ติดต่อ */
  phone: string;
  /** อีเมลผู้ใช้งาน */
  email: string;
  /** บทบาทในระบบ: 'buyer' (ผู้ซื้อ/ลูกค้า), 'agent' (นายหน้า), 'admin' (ผู้ดูแลระบบ) */
  role: 'buyer' | 'agent' | 'admin';
}

